#!/usr/bin/env node
/**
 * Emit the disposition chip vocabulary as JSON for cross-repo readers.
 *
 * The chip sets are UI-owned on purpose (2026-06-14: the wire enums are
 * open strings and `DismissReason`'s own docstring puts the vocabulary
 * here). But the agents-side chip-usage report needs them to join
 * "what was offered" against "what was picked", and until now it
 * regex-parsed this module — the last thing crossing the repo boundary
 * by formatting rather than by contract.
 *
 * Output: `generated/chipSets.json`, committed. Neither repo builds the
 * other; the agents side reads the committed file.
 *
 * Run: `npm run emit:chip-sets` (from apps/curation).
 * Guarded by `chipSetsJson.test.ts`, which fails if the committed JSON
 * drifts from the module — so a chip added without re-emitting is
 * caught in the pre-commit gate rather than silently under-reporting.
 */
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = join(here, "..");
const SOURCE = join(appRoot, "src/features/audit/dispositionChips.ts");
const OUT = join(appRoot, "generated/chipSets.json");

/** Transform the TS module to ESM in a temp file, then import it.
 *  Type-only imports vanish, so nothing else needs resolving. */
const tmp = join(appRoot, "generated/.chipSets.tmp.mjs");
mkdirSync(dirname(tmp), { recursive: true });
await build({
  entryPoints: [SOURCE],
  outfile: tmp,
  format: "esm",
  platform: "node",
  bundle: false,
  logLevel: "warning",
});
const mod = await import(pathToFileURL(tmp).href + `?t=${process.pid}`);

// 🛑 Deprecated aliases (`CAL_MISS_DISMISS_CHIPS = CAL_MISS_FACTOR_
// DISMISS_CHIPS`) are the SAME array, not a copy. Emitting both would
// double-count every one of its chips in any usage join — the report
// would read one dialog as two.
//
// Which name is canonical comes from the SOURCE, not from iteration
// order: an ESM namespace object has its keys sorted alphabetically,
// so `CAL_MISS_DISMISS_CHIPS` arrives before the set it aliases and a
// first-wins rule crowns the deprecated name. Deterministic and
// backwards. A real definition is the one written `: DialogChip[] = [`.
const source = readFileSync(SOURCE, "utf8");
const declared = new Set(
  [...source.matchAll(/export const (\w+): DialogChip\[\] = \[/g)].map(
    (m) => m[1],
  ),
);
if (declared.size === 0) {
  console.error("✗ found no chip-set declarations — has the syntax changed?");
  process.exit(1);
}

const sets = {};
const aliases = {};
const canonicalOf = new Map(); // array identity -> canonical export name
for (const [name, value] of Object.entries(mod)) {
  if (!Array.isArray(value)) continue;
  if (!value.every((c) => c && typeof c.key === "string")) continue;
  if (!declared.has(name)) continue;
  canonicalOf.set(value, name);
  sets[name] = value.map((c) => ({
    key: c.key,
    label: c.label,
    help: c.help,
    added: c.added,
  }));
}
for (const [name, value] of Object.entries(mod)) {
  if (!Array.isArray(value) || declared.has(name)) continue;
  const canonical = canonicalOf.get(value);
  if (canonical) aliases[name] = canonical;
}

const missingDates = Object.entries(sets).flatMap(([s, chips]) =>
  chips.filter((c) => !c.added).map((c) => `${s}.${c.key}`),
);
if (missingDates.length) {
  console.error(`✗ chips with no 'added' date:\n  ${missingDates.join("\n  ")}`);
  process.exit(1);
}

// Sorted keys so the committed file has a stable diff — a reordered
// chip should show as a reorder, not as a whole-file rewrite.
const payload = {
  $comment:
    "GENERATED by apps/curation/scripts/emit-chip-sets.mjs — do not edit. " +
    "Source of truth: apps/curation/src/features/audit/dispositionChips.ts. " +
    "'added' is the ISO date a chip was first offered in that set; filter " +
    "on it before reading 'offered but never picked', since a chip younger " +
    "than the dispositions being tallied cannot have been refused.",
  sets: Object.fromEntries(
    Object.keys(sets)
      .sort()
      .map((k) => [k, sets[k]]),
  ),
  /** Deprecated export name → the set it points at. Same array, not a
   *  copy; resolve through this rather than treating it as a set. */
  aliases,
};

writeFileSync(OUT, JSON.stringify(payload, null, 2) + "\n");
const { rmSync } = await import("node:fs");
rmSync(tmp, { force: true });
console.log(
  `wrote ${OUT} — ${Object.keys(sets).length} sets, ` +
    `${Object.values(sets).reduce((n, s) => n + s.length, 0)} chips`,
);
