#!/usr/bin/env node
/**
 * Emit `packages/ui/src/GemmaMark.tsx` — the Gemma mark as an inline-SVG
 * React component, drawn in `currentColor`.
 *
 * Why a component rather than the `gemmaMark` asset URL: an `<img src>` is
 * an opaque box, and CSS does not reach inside it. The curation app's
 * header is stone-900 text on stone-100 in light mode and slate-100 on
 * slate-900 in dark, and a monochrome mark there has to follow the label
 * beside it. Only an INLINE svg can inherit `currentColor`, so only an
 * inline svg gives one asset that is correct in both themes with no
 * variant, no media query and no second file to keep in step.
 *
 * Why generated rather than hand-written: the alternative is pasting the
 * mark's 13 path strings into a .tsx, which forks the artwork. The next
 * person to re-export the logo updates the .svg and the component keeps
 * drawing the old shape, silently — the same drift the favicons are
 * generated to avoid. `gemmaMarkComponent.test.ts` fails if the committed
 * component stops matching the mark.
 *
 * The mark's box is portrait (aspect 0.93), so the component takes a
 * `size` that means HEIGHT and lets width follow — a caller lining it up
 * with a line of text is matching cap height, not width.
 *
 * Run: `npm run emit:mark-component` (from apps/curation).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { MARK_PATH, readMark } from "./emit-favicon.mjs";

const here = dirname(fileURLToPath(import.meta.url));

export const COMPONENT_PATH = join(here, "../../ui/src/GemmaMark.tsx");

/** Build the component source from the mark's own source text. Pure — the
 *  test calls this and compares. */
export function buildMarkComponent(markSvg) {
  const { w, h, paths } = readMark(markSvg);
  // currentColor, and nothing else: a per-path fill here would pin the
  // mark to one theme, which is the entire point of the component.
  const bare = paths.map((p) => p.replace(/\s*fill="#[0-9a-f]{6}"/, ""));

  return `/**
 * GENERATED by packages/assets/scripts/emit-mark-component.mjs from
 * packages/assets/src/images/logo/gemma-mark.svg — do not edit by hand.
 * Run \`npm run emit:mark-component\` after the mark changes.
 *
 * The Gemma mark as inline SVG, drawn in \`currentColor\` so it takes the
 * colour of the text around it — one asset that is correct in light and
 * dark mode with no variant. For the mark in its brand colours, import
 * \`gemmaMark\` (or \`gemmaLockup\`) from \`@gemma/assets\` instead; that is
 * an \`<img src>\` and does not inherit anything.
 *
 * \`size\` is the HEIGHT in px. The mark's box is portrait (${w} x ${h},
 * aspect ${(w / h).toFixed(3)}), so width follows from it — a caller placing
 * this beside text is matching cap height, not width.
 */
export function GemmaMark({
  size = 16,
  className,
  title,
}: {
  size?: number;
  className?: string;
  /** Accessible name. Omit it on a mark that sits beside the word
   *  "Gemma" — the label already says it, and a second one makes a
   *  screen reader read the brand twice. */
  title?: string;
}) {
  return (
    <svg
      viewBox="0 0 ${w} ${h}"
      height={size}
      width={size * ${(w / h).toFixed(6)}}
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      className={className}
      style={{ display: "block", flexShrink: 0 }}
    >
      {title ? <title>{title}</title> : null}
${bare.map((p) => `      ${p.replace(/\/>$/, " />")}`).join("\n")}
    </svg>
  );
}
`;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
) {
  const src = buildMarkComponent(readFileSync(MARK_PATH, "utf8"));
  writeFileSync(COMPONENT_PATH, src);
  process.stdout.write(`emit-mark-component: wrote ${COMPONENT_PATH}\n`);
}
